/* ─── Emit ──────────────────────────────────────────────────────── */

function writeIfChanged(file, contents) {
  const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (existing === contents) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents, 'utf8');
  return true;
}

/** Remove pages this build no longer owns. Only ever touches generated files. */
function sweepStalePages(liveSlugs) {
  const removed = [];
  for (const entry of fs.readdirSync(HERE, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    if (['data', 'photos', 'guides'].includes(entry.name)) continue;
    const page = path.join(HERE, entry.name, 'index.html');
    if (!fs.existsSync(page)) continue;
    if (!fs.readFileSync(page, 'utf8').includes(GENERATED_MARKER)) continue;
    if (liveSlugs.has(entry.name)) continue;
    fs.rmSync(page);
    if (fs.readdirSync(path.join(HERE, entry.name)).length === 0) {
      fs.rmdirSync(path.join(HERE, entry.name));
    }
    removed.push(entry.name);
  }
  return removed;
}

/**
 * A site that is not live must never leave a dangling URL.
 *   suspended -> 302, it is expected back
 *   archived  -> 301, the agent has left and the URL is permanently the directory
 *   draft     -> nothing; the page has never existed publicly, so it 404s
 */
function redirectRules(agents) {
  const lines = [];
  for (const { agent } of agents) {
    const { status } = agent.delivery;
    if (status === 'live' || status === 'draft') continue;
    const code = status === 'archived' ? 301 : 302;
    const slug = agent.identity.slug;
    lines.push(`# ${agent.identity.name} — ${status}`);
    lines.push(`/agents/${slug}      /agents/   ${code}`);
    lines.push(`/agents/${slug}/*    /agents/   ${code}`);
  }
  return lines;
}

function writeRedirects(lines) {
  const block = [REDIRECTS_BEGIN, ...lines, REDIRECTS_END].join('\n');
  let existing = fs.existsSync(REDIRECTS_FILE) ? fs.readFileSync(REDIRECTS_FILE, 'utf8') : '';
  const start = existing.indexOf(REDIRECTS_BEGIN);
  const end = existing.indexOf(REDIRECTS_END);
  if (start !== -1 && end !== -1) {
    existing = existing.slice(0, start) + block + existing.slice(end + REDIRECTS_END.length);
  } else {
    existing = existing.trim() ? `${existing.trimEnd()}\n\n${block}` : block;
  }
  return writeIfChanged(REDIRECTS_FILE, `${existing.trimEnd()}\n`);
}

/* ─── Main ──────────────────────────────────────────────────────── */

function fail(message, details = []) {
  console.error(`\n✗  ${message}`);
  for (const d of details) console.error(`   ${d}`);
  console.error('');
  process.exit(1);
}

function main() {
  const site = JSON.parse(fs.readFileSync(SITE_CONFIG, 'utf8'));
  const { origin, source: originSource } = resolveOrigin(site);
  if (!origin) {
    fail('No site origin. Set "origin" in agents/site.json, or CB_SITE_ORIGIN in the environment.');
  }

  const files = fs.readdirSync(DATA_DIR).filter((f) => f.endsWith('.json')).sort();
  if (files.length === 0) fail(`No agent data in ${path.relative(ROOT, DATA_DIR)}/`);

  const errors = [];
  const warnings = [];
  const seenSlugs = new Map();
  const parsed = [];

  for (const file of files) {
    let agent;
    try {
      agent = JSON.parse(fs.readFileSync(path.join(DATA_DIR, file), 'utf8'));
    } catch (e) {
      errors.push(`${file}: is not valid JSON — ${e.message}`);
      continue;
    }
    const v = validateAgent(agent, file, seenSlugs);
    errors.push(...v.errors);
    warnings.push(...v.warnings);
    if (v.errors.length === 0) parsed.push({ file, agent });
  }

  if (errors.length > 0) {
    fail(`${errors.length} problem${errors.length === 1 ? '' : 's'} in agents/data — nothing was written.`, errors);
  }

  for (const w of warnings) console.warn(`!  ${w}`);

  const live = parsed.filter(({ agent }) => agent.delivery.status === 'live');
  const liveSlugs = new Set(live.map(({ agent }) => agent.identity.slug));

  const agentNodes = parseTemplate(fs.readFileSync(AGENT_TEMPLATE, 'utf8'), 'template.html');
  const dirNodes = parseTemplate(fs.readFileSync(DIRECTORY_TEMPLATE, 'utf8'), 'directory.template.html');

  const models = live.map(({ agent }) => buildAgentModel(agent, site, origin));
  // Render everything before writing anything, so a template error cannot
  // leave half a directory of pages behind.
  const pages = models.map((model) => ({
    slug: model.SLUG,
    file: path.join(HERE, model.SLUG, 'index.html'),
    html: `<!-- ${GENERATED_MARKER} from agents/data/${model.SLUG}.json — edit the JSON, not this file. -->\n`
      + render(agentNodes, model, `template.html (${model.SLUG})`),
  }));

  const neighborhoodCounts = new Map();
  for (const model of models) {
    for (const { NEIGHBORHOOD } of model.NEIGHBORHOODS) {
      neighborhoodCounts.set(NEIGHBORHOOD, (neighborhoodCounts.get(NEIGHBORHOOD) ?? 0) + 1);
    }
  }
  const filters = [...neighborhoodCounts.entries()]
    .filter(([, count]) => count >= 2)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, 8)
    .map(([name]) => ({ FILTER_SLUG: slugify(name), FILTER_LABEL: name }));

  const directoryModel = {
    AGENTS: models.map((m) => ({
      CARD_SLUG: m.SLUG,
      CARD_NAME: m.NAME,
      CARD_TITLE: m.TITLE,
      CARD_INITIALS: initialsOf(m.NAME),
      CARD_PHOTO_BLOCK: m.DIR_PHOTO_BLOCK,
      CARD_COLOR_A: m.PHOTO_COLOR_A,
      CARD_COLOR_B: m.PHOTO_COLOR_B,
      CARD_NEIGHBORHOODS: m.NEIGHBORHOODS,
      CARD_NEIGHBORHOOD_KEYS: m.NEIGHBORHOODS.map((n) => slugify(n.NEIGHBORHOOD)).join('|'),
      CARD_LANGUAGES: m.LANGUAGE_LIST,
      CARD_HAS_LANGUAGES: m.HAS_LANGUAGES,
    })),
    HAS_AGENTS: models.length > 0,
    FILTERS: filters,
    HAS_FILTERS: filters.length >= 2,
    AGENT_COUNT: models.length,
    BROKERAGE_NAME: site.brokerage.name,
    BROKERAGE_FOUNDED: site.brokerage.foundedYear,
    BROKERAGE_ADDRESS_LINE1: site.brokerage.address.line1,
    BROKERAGE_ADDRESS_LINE2: `${site.brokerage.address.city}, ${site.brokerage.address.state}`,
    CANONICAL_URL: `${origin}/agents/`,
    YEAR: new Date().getFullYear(),
  };
  const directoryHtml = `<!-- ${GENERATED_MARKER} from agents/data/*.json — edit directory.template.html, not this file. -->\n`
    + render(dirNodes, directoryModel, 'directory.template.html');

  const redirects = redirectRules(parsed);

  console.log(`\nCasa Blanca — agent sites`);
  console.log(`   origin      ${origin}  (from ${originSource})`);
  if (originSource !== 'environment' && site.originConfirmed !== true) {
    console.warn('!  agents/site.json "origin" is an unconfirmed placeholder. Netlify\'s URL env var'
      + '\n   overrides it on deploy, so this only affects local builds — but confirm the real'
      + '\n   Netlify site name with Kimani and set "originConfirmed": true.');
  }
  console.log(`   agents      ${parsed.length} on file · ${live.length} live`);

  if (CHECK_ONLY) {
    console.log(`\n✓  ${files.length} agent file${files.length === 1 ? '' : 's'} valid. --check, so nothing was written.\n`);
    return;
  }

  let written = 0;
  for (const page of pages) {
    if (writeIfChanged(page.file, page.html)) written++;
    console.log(`   built       /agents/${page.slug}/`);
  }
  if (writeIfChanged(path.join(HERE, 'index.html'), directoryHtml)) written++;
  console.log(`   built       /agents/  (directory)`);

  for (const slug of sweepStalePages(liveSlugs)) {
    console.log(`   removed     /agents/${slug}/  (no longer live)`);
  }
  for (const { agent } of parsed) {
    if (agent.delivery.status !== 'live') {
      console.log(`   ${agent.delivery.status.padEnd(11)} /agents/${agent.identity.slug}/  → redirect to /agents/`);
    }
  }
  if (writeRedirects(redirects)) {
    console.log(`   built       /_redirects  (${redirects.filter((l) => !l.startsWith('#')).length} rule(s))`);
  }

  console.log(`\n✓  Done — ${written} file${written === 1 ? '' : 's'} changed.\n`);
}

try {
  main();
} catch (error) {
  fail(error.message, error.stack ? error.stack.split('\n').slice(1, 4) : []);
}
