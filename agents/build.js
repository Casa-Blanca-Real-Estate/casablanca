    SPECIALTIES: specialties.map((s) => ({ SPECIALTY: s })),
    STATS: statRow,
    ACCEPTING_CLIENTS: profile.acceptingClients === true,
    TESTIMONIALS: (profile.testimonials ?? []).map((t) => ({
      QUOTE: t.quote,
      AUTHOR: t.author,
      AUTHOR_INITIALS: initialsOf(t.author),
      DETAIL: t.detail ?? '',
      HAS_DETAIL: Boolean(t.detail),
      SOURCE: t.source,
      DATE: t.date,
    })),
    DEALS: (agent.deals ?? []).map((d) => ({
      DEAL_ADDRESS: d.unit ? `${d.address}, ${d.unit}` : d.address,
      DEAL_META: [
        Number.isInteger(d.squareFeet) ? `${NUM.format(d.squareFeet)} sq ft` : '',
        Number.isInteger(d.price) ? USD.format(d.price) : '',
      ].filter(Boolean).join(' · '),
    })),

    PHOTO_BLOCK: heroPhoto,
